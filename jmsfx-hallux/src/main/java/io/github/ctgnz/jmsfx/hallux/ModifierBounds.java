package io.github.ctgnz.jmsfx.hallux;

import java.util.Map;

import javafx.geometry.Rectangle2D;

import io.github.ctgnz.jmsfx.IconGeometry;

/**
 * Bounds for the sector modifier fragments that draw outside the bounding octagon.
 * <p>
 * APP-6E places sector modifiers within the octagon, and all but a handful do, so {@link IconGeometry#OCTAGON} serves as their bounds without measuring each one. The exceptions
 * are genuine rather than drawing errors - the Land Units supply bar and headquarters rule are full-width horizontal rules, for instance - so they carry measured bounds here.
 * <p>
 * Generated by {@code FragmentMeasurer}; do not edit. Keyed by graphic identifier, which is the fragment's file stem.
 */
public final class ModifierBounds {

    private static final Map<String, Rectangle2D> BOUNDS = Map.ofEntries(
        Map.entry("10622", new Rectangle2D(121, 442.52, 370, 5.28)),
        Map.entry("10941", new Rectangle2D(186.83, 292.78, 249.83, 52.35)),
        Map.entry("10981", new Rectangle2D(131.5, 342.5, 348, 5)));

    /**
     * The bounds of the fragment with this identifier, or {@link IconGeometry#OCTAGON} when it keeps within the octagon like the great majority.
     */
    public static Rectangle2D lookup(String graphicIdentifier) {
        return BOUNDS.getOrDefault(graphicIdentifier, IconGeometry.OCTAGON);
    }

    private ModifierBounds() {
    }

}
